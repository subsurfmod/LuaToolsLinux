//! PlayUnownedService — manages `play_unowned_games.lua` in `stplug-in/` and keeps
//! SLSsteam `PlayNotOwnedGames`, `AdditionalApps`, and `FakeAppIds` synchronized across
//! multiple unowned titles without overwriting previous games.

use std::fs;
use std::path::PathBuf;

use crate::models::steam::SteamInstallation;
use crate::services::slssteam_service::SlssteamService;

pub const PLUGIN_FILENAME: &str = "play_unowned_games.lua";

#[derive(Debug, Clone, Default)]
pub struct PlayUnownedService {
    pub steam_installation: Option<SteamInstallation>,
}

impl PlayUnownedService {
    pub fn new(steam_installation: Option<SteamInstallation>) -> Self {
        Self { steam_installation }
    }

    pub fn stplug_in_dir(&self) -> Option<PathBuf> {
        self.steam_installation
            .as_ref()
            .filter(|i| !i.stplug_in_path.as_os_str().is_empty())
            .map(|i| i.stplug_in_path.clone())
    }

    pub fn lua_path(&self) -> Option<PathBuf> {
        self.stplug_in_dir().map(|d| d.join(PLUGIN_FILENAME))
    }

    pub fn is_installed(&self) -> bool {
        self.lua_path().map(|p| p.is_file()).unwrap_or(false)
    }

    pub fn is_enabled(&self, sls: &SlssteamService) -> bool {
        sls.config.play_not_owned
    }

    pub fn is_app_enabled(&self, app_id: u32, sls: &SlssteamService) -> bool {
        sls.config.play_not_owned && sls.config.additional_apps.contains(&app_id)
    }

    pub fn get_managed_app_ids(&self, sls: &SlssteamService) -> Vec<u32> {
        let mut ids = sls.config.additional_apps.clone();
        ids.sort_unstable();
        ids.dedup();
        ids
    }

    /// Synchronizes `stplug-in/play_unowned_games.lua` to match `sls.config`.
    pub fn sync_plugin_file(&self, sls: &SlssteamService) -> Result<Option<PathBuf>, String> {
        let Some(lua_file) = self.lua_path() else {
            return Ok(None);
        };
        if !sls.config.play_not_owned {
            if lua_file.exists() {
                let _ = fs::remove_file(&lua_file);
            }
            return Ok(None);
        }

        let Some(stplug) = self.stplug_in_dir() else {
            return Ok(None);
        };
        fs::create_dir_all(&stplug)
            .map_err(|e| format!("Failed to create stplug-in dir: {}", e))?;

        let managed = self.get_managed_app_ids(sls);
        let mut out = String::from(
            "-- PlayUnownedGames — multi-app unowned game entitlement helper\n\
             -- Auto-generated by LuaTools Linux\n\n",
        );

        // Emit addappid() only for managed apps that do not already have a dedicated <appid>.lua
        for &aid in &managed {
            if aid == 0 {
                continue;
            }
            let dedicated = stplug.join(format!("{}.lua", aid));
            if !dedicated.exists() && type_safe_addappid_line(&mut out, aid) {
                // added fallback entitlement line
            }
        }

        out.push_str("\nlocal UNOWNED_APPS = {\n");
        for &aid in &managed {
            if aid > 0 {
                out.push_str(&format!("    [{}] = true,\n", aid));
            }
        }
        out.push_str("}\n\n");

        // Guard `steam_api` checks with `type(steam_api) == \"table\"` so Lua runtimes that
        // only expose addappid/setManifestid never abort on nil global indexing.
        out.push_str(
            "if type(steam_api) == \"table\" then\n\
             \x20   local function is_spoofed(appid)\n\
             \x20       return UNOWNED_APPS[appid] == true or next(UNOWNED_APPS) == nil\n\
             \x20   end\n\
             \x20   if type(steam_api.ISteamUser) == \"function\" then\n\
             \x20       local steam_user = steam_api.ISteamUser()\n\
             \x20       if steam_user and steam_user.Original_BIsSubscribedApp then\n\
             \x20           steam_user.BIsSubscribedApp = function(appid)\n\
             \x20               if is_spoofed(appid) then return true end\n\
             \x20               return steam_user:Original_BIsSubscribedApp(appid)\n\
             \x20           end\n\
             \x20       end\n\
             \x20   end\n\
             \x20   if type(steam_api.ISteamApps) == \"function\" then\n\
             \x20       local steam_apps = steam_api.ISteamApps()\n\
             \x20       if steam_apps and steam_apps.Original_BIsSubscribedApp then\n\
             \x20           steam_apps.BIsSubscribedApp = function(appid)\n\
             \x20               if is_spoofed(appid) then return true end\n\
             \x20               return steam_apps:Original_BIsSubscribedApp(appid)\n\
             \x20           end\n\
             \x20       end\n\
             \x20   end\n\
             end\n",
        );

        fs::write(&lua_file, out)
            .map_err(|e| format!("Failed to write {}: {}", lua_file.display(), e))?;
        Ok(Some(lua_file))
    }

    pub fn set_enabled(&self, enabled: bool, sls: &mut SlssteamService) -> Result<(), String> {
        sls.config.play_not_owned = enabled;
        if !sls.save() {
            return Err("Failed to save SLSsteam config.yaml".into());
        }
        self.sync_plugin_file(sls)?;
        Ok(())
    }

    pub fn enable_for_app(&self, app_id: u32, sls: &mut SlssteamService) -> Result<(), String> {
        sls.add_additional_app(app_id);
        if sls.get_fake_app_id(app_id).is_none() {
            sls.set_fake_app_id(app_id, 480);
        }
        sls.config.play_not_owned = true;
        if !sls.save() {
            return Err("Failed to save SLSsteam config.yaml".into());
        }
        self.sync_plugin_file(sls)?;
        Ok(())
    }

    pub fn disable_for_app(&self, app_id: u32, sls: &mut SlssteamService) -> Result<(), String> {
        sls.remove_additional_app(app_id);
        if sls.get_fake_app_id(app_id) == Some(480) {
            sls.remove_fake_app_id(app_id);
        }
        if !sls.save() {
            return Err("Failed to save SLSsteam config.yaml".into());
        }
        self.sync_plugin_file(sls)?;
        Ok(())
    }
}

fn type_safe_addappid_line(buf: &mut String, app_id: u32) -> bool {
    buf.push_str(&format!(
        "if type(addappid) == \"function\" then addappid({}) end\n",
        app_id
    ));
    true
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::steam::SteamLibrary;

    #[test]
    fn preserves_multiple_managed_apps_and_cleans_up_on_disable() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().join("Steam");
        let stplug = root.join("config/stplug-in");
        fs::create_dir_all(&stplug).unwrap();

        let inst = SteamInstallation {
            root: root.clone(),
            libraries: vec![SteamLibrary::new(root.clone())],
            config_path: root.join("config"),
            stplug_in_path: stplug.clone(),
        };
        let mut sls = SlssteamService::new(Some(tmp.path().join("SLSsteam/config.yaml")));
        let svc = PlayUnownedService::new(Some(inst));

        svc.enable_for_app(1245620, &mut sls).unwrap();
        svc.enable_for_app(1091500, &mut sls).unwrap();
        assert!(svc.is_installed());
        assert!(svc.is_app_enabled(1245620, &sls));
        assert!(svc.is_app_enabled(1091500, &sls));

        let lua = fs::read_to_string(svc.lua_path().unwrap()).unwrap();
        assert!(lua.contains("[1245620] = true"));
        assert!(lua.contains("[1091500] = true"));
        assert!(lua.contains("type(steam_api) == \"table\""));

        // Disabling one app keeps the other app active
        svc.disable_for_app(1245620, &mut sls).unwrap();
        let lua_after = fs::read_to_string(svc.lua_path().unwrap()).unwrap();
        assert!(!lua_after.contains("[1245620] = true"));
        assert!(lua_after.contains("[1091500] = true"));

        // Turning off PlayNotOwnedGames removes play_unowned_games.lua cleanly
        svc.set_enabled(false, &mut sls).unwrap();
        assert!(!svc.is_installed());
    }
}
