"""LuaTools service - manages stplug-in lua files for depot configuration."""

from __future__ import annotations

from pathlib import Path
from typing import Optional

from ..models.steam import (
    get_lua_file_path,
    get_stplug_in_dir,
    read_lua_file,
    write_lua_file,
)


class LuaToolsService:
    """Service for managing stplug-in lua files."""

    def __init__(self, stplug_in_dir: Optional[Path] = None) -> None:
        if stplug_in_dir is None:
            stplug_in_dir = Path.home() / ".local/share/Steam/config/stplug-in"
        self.stplug_in_dir = stplug_in_dir
        self.stplug_in_dir.mkdir(parents=True, exist_ok=True)

    def lua_path(self, app_id: int) -> Path:
        return get_lua_file_path(self.stplug_in_dir, app_id)

    def read_lua(self, app_id: int) -> str:
        return read_lua_file(self.lua_path(app_id))

    def write_lua(self, app_id: int, content: str) -> bool:
        try:
            write_lua_file(self.lua_path(app_id), content)
            return True
        except Exception:
            return False

    def delete_lua(self, app_id: int) -> bool:
        try:
            path = self.lua_path(app_id)
            if path.exists():
                path.unlink()
            return True
        except Exception:
            return False

    def lua_exists(self, app_id: int) -> bool:
        return self.lua_path(app_id).exists()

    def list_lua_files(self) -> list[int]:
        """List all app IDs that have lua files in stplug-in."""
        app_ids = []
        if self.stplug_in_dir.exists():
            for f in self.stplug_in_dir.glob("*.lua"):
                try:
                    app_ids.append(int(f.stem))
                except ValueError:
                    continue
        return sorted(app_ids)

    @staticmethod
    def default_lua_content(app_id: int) -> str:
        """Generate default lua file content for an app."""
        return f"""-- LuaTools configuration for AppID {app_id}
-- Generated by LuaTools Linux

-- Depot pinning example:
-- DepotPin({app_id}, 480)

-- Per-depot enable/disable:
-- DepotEnable({app_id}, 480, true)
-- DepotDisable({app_id}, 480, false)

return {{
    appid = {app_id},
    enabled = true,
}}
"""
